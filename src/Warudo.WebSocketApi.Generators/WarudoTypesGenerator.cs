using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Warudo.WebSocketApi.Generators;

/// <summary>
/// Reads <c>warudo-types.txt</c>, the asset and node types tools/SchemaExport reads from a Warudo install, and
/// emits a typed class per type for Warudo.Client: an accessor pair per data input and a method per trigger for
/// assets, and typed input properties with a typed result for nodes. Everything goes through the generic
/// entity and node methods, so a type that is not in the table stays reachable.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class WarudoTypesGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor _badLine = new(
        "WARUDOGEN002",
        "Unreadable type line",
        "Line {0} of warudo-types.txt is not a type or a port: {1}",
        "Warudo.WebSocketApi.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    private static readonly HashSet<string> _reserved = new(StringComparer.Ordinal)
    {
        "TypeId",
        "AssetTypeId",
        "NodeTypeId",
        "Id",
        "Client",
        "Outputs",
        "FlowInputs",
        "RunAsync",
        "AddAsync",
        "AddToBlueprintAsync",
        "RenameAsync",
        "RemoveAsync",
        "ExportAsync",
        "DescribeAsync",
        "WatchAsync",
        "Equals",
        "GetHashCode",
        "ToString",
        "GetType",
        "WriteInputs",
    };

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<string> side = context.AnalyzerConfigOptionsProvider.Select(
            static (options, _) =>
                options.GlobalOptions.TryGetValue("build_property.WarudoApiSide", out string? value)
                    ? value
                    : string.Empty
        );
        IncrementalValuesProvider<string> tables = context
            .AdditionalTextsProvider.Where(static file =>
                file.Path.EndsWith("warudo-types.txt", StringComparison.OrdinalIgnoreCase)
            )
            .Select(static (file, ct) => file.GetText(ct)?.ToString() ?? string.Empty);
        context.RegisterSourceOutput(
            tables.Combine(side),
            static (spc, input) =>
            {
                if (string.Equals(input.Right, "Client", StringComparison.OrdinalIgnoreCase))
                {
                    Emit(spc, input.Left);
                }
            }
        );
    }

    private static void Emit(SourceProductionContext context, string table)
    {
        List<WarudoType> types = [];
        string[] lines = table.Split('\n');
        for (int index = 0; index < lines.Length; index++)
        {
            string line = lines[index].TrimEnd('\r');
            if (line.Trim().Length == 0 || line[0] == '#')
            {
                continue;
            }

            string[] fields = line.Split('\t');
            if (line[0] != '\t' && fields.Length >= 5 && fields[0] is "asset" or "node")
            {
                types.Add(
                    new WarudoType(fields[0] == "node", fields[1], fields[2], fields[3], fields[4])
                );
            }
            else if (line[0] == '\t' && types.Count > 0 && Port.TryParse(fields) is { } port)
            {
                types[types.Count - 1].Ports.Add(port);
            }
            else
            {
                context.ReportDiagnostic(
                    Diagnostic.Create(_badLine, Location.None, index + 1, line)
                );
            }
        }

        StringBuilder assets = Header("Warudo.Client.Assets");
        StringBuilder nodes = Header("Warudo.Client.Nodes");
        foreach (WarudoType type in types)
        {
            if (type.IsNode)
            {
                Node(nodes, type);
            }
            else
            {
                Asset(assets, type);
            }
        }

        context.AddSource("WarudoAssets.g.cs", SourceText.From(assets.ToString(), Encoding.UTF8));
        context.AddSource("WarudoNodes.g.cs", SourceText.From(nodes.ToString(), Encoding.UTF8));
    }

    private static StringBuilder Header(string ns)
    {
        StringBuilder s = new();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("using System;");
        s.AppendLine("using System.Text.Json;");
        s.AppendLine("using System.Text.Json.Nodes;");
        s.AppendLine("using System.Threading;");
        s.AppendLine("using System.Threading.Tasks;");
        s.AppendLine();
        s.AppendLine($"namespace {ns};");
        s.AppendLine();
        return s;
    }

    private static void Asset(StringBuilder s, WarudoType type)
    {
        s.AppendLine(
            $"/// <summary>Warudo's <c>{Escape(type.Title)}</c> asset ({Escape(type.Category)}).</summary>"
        );
        s.AppendLine(
            $"public sealed partial class {type.Class} : global::Warudo.Client.WarudoAsset"
        );
        s.AppendLine("{");
        s.AppendLine("    /// <summary>The asset type's id.</summary>");
        s.AppendLine($"    public const string AssetTypeId = \"{type.Id}\";");
        s.AppendLine();
        s.AppendLine("    /// <summary>An asset of this type that is in the scene.</summary>");
        s.AppendLine("    /// <param name=\"client\">The connection.</param>");
        s.AppendLine("    /// <param name=\"id\">The asset's id.</param>");
        s.AppendLine(
            $"    public {type.Class}(global::Warudo.Client.WarudoClient client, Guid id) : base(client, id) {{ }}"
        );
        s.AppendLine();
        s.AppendLine("    /// <summary>Adds an asset of this type to the opened scene.</summary>");
        s.AppendLine("    /// <param name=\"client\">The connection.</param>");
        s.AppendLine("    /// <param name=\"name\">Its name, or Warudo's default.</param>");
        s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
        s.AppendLine("    /// <returns>The new asset.</returns>");
        s.AppendLine(
            $"    public static async Task<{type.Class}> AddAsync(global::Warudo.Client.WarudoClient client, string? name = null, CancellationToken ct = default)"
        );
        s.AppendLine("    {");
        s.AppendLine("        ArgumentNullException.ThrowIfNull(client);");
        s.AppendLine(
            $"        return new {type.Class}(client, await client.AssetAddAsync(AssetTypeId, name, ct).ConfigureAwait(false));"
        );
        s.AppendLine("    }");
        Enums(s, type);
        HashSet<string> used = new(StringComparer.Ordinal);
        foreach (Port port in type.Ports.Where(static p => p.Section == "input"))
        {
            string name = Member(port.Key, type.Class, used);
            s.AppendLine();
            s.AppendLine(
                $"    /// <summary>The <c>{Escape(port.Key)}</c> data input{Label(port)}.</summary>"
            );
            s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
            s.AppendLine("    /// <returns>Its value.</returns>");
            s.AppendLine(
                $"    public async Task<{port.ClientType}> Get{name}Async(CancellationToken ct = default) => {port.Read($"await GetInputAsync(\"{port.Key}\", ct).ConfigureAwait(false)")};"
            );
            s.AppendLine();
            s.AppendLine(
                $"    /// <summary>Sets the <c>{Escape(port.Key)}</c> data input{Label(port)}.</summary>"
            );
            s.AppendLine("    /// <param name=\"value\">The value.</param>");
            s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
            s.AppendLine("    /// <returns>When it is set.</returns>");
            s.AppendLine(
                $"    public Task Set{name}Async({port.ClientType} value, CancellationToken ct = default) => SetInputAsync(\"{port.Key}\", {port.Write("value")}, ct);"
            );
        }

        foreach (Port port in type.Ports.Where(static p => p.Section == "trigger"))
        {
            string name = Member(port.Key, type.Class, used);
            s.AppendLine();
            s.AppendLine(
                $"    /// <summary>Invokes the <c>{Escape(port.Key)}</c> trigger{Label(port)}.</summary>"
            );
            s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
            s.AppendLine("    /// <returns>When it ran.</returns>");
            s.AppendLine(
                $"    public Task {name}Async(CancellationToken ct = default) => InvokeTriggerAsync(\"{port.Key}\", ct);"
            );
        }

        s.AppendLine("}");
        s.AppendLine();
    }

    private static void Node(StringBuilder s, WarudoType type)
    {
        List<Port> inputs = [.. type.Ports.Where(static p => p.Section == "input")];
        List<Port> outputs = [.. type.Ports.Where(static p => p.Section == "output")];
        List<Port> flows = [.. type.Ports.Where(static p => p.Section == "flowInput")];
        s.AppendLine(
            $"/// <summary>Warudo's <c>{Escape(type.Title)}</c> node ({Escape(type.Category)}).</summary>"
        );
        s.AppendLine(
            $"public sealed partial class {type.Class} : global::Warudo.Client.WarudoNode"
        );
        s.AppendLine("{");
        s.AppendLine("    /// <summary>The node type's id.</summary>");
        s.AppendLine($"    public const string NodeTypeId = \"{type.Id}\";");
        s.AppendLine();
        s.AppendLine("    /// <inheritdoc/>");
        s.AppendLine("    public override string TypeId => NodeTypeId;");
        Enums(s, type);
        if (flows.Count > 0)
        {
            s.AppendLine();
            s.AppendLine("    /// <summary>The node's flow inputs.</summary>");
            s.AppendLine("    public static class FlowInputs");
            s.AppendLine("    {");
            HashSet<string> flowNames = new(StringComparer.Ordinal);
            foreach (Port flow in flows)
            {
                s.AppendLine(
                    $"        /// <summary>The <c>{Escape(flow.Key)}</c> flow input.</summary>"
                );
                s.AppendLine(
                    $"        public const string {Member(flow.Key, "FlowInputs", flowNames)} = \"{flow.Key}\";"
                );
            }

            s.AppendLine("    }");
        }

        HashSet<string> used = new(StringComparer.Ordinal);
        List<(Port Port, string Name)> properties = [];
        foreach (Port port in inputs)
        {
            string name = Member(port.Key, type.Class, used);
            properties.Add((port, name));
            s.AppendLine();
            s.AppendLine(
                $"    /// <summary>The <c>{Escape(port.Key)}</c> data input{Label(port)}; left unset, Warudo's default applies.</summary>"
            );
            s.AppendLine($"    public {port.ClientType.TrimEnd('?')}? {name} {{ get; set; }}");
        }

        s.AppendLine();
        s.AppendLine("    /// <inheritdoc/>");
        s.AppendLine("    protected override void WriteInputs(JsonObject inputs)");
        s.AppendLine("    {");
        s.AppendLine("        ArgumentNullException.ThrowIfNull(inputs);");
        foreach ((Port port, string name) in properties)
        {
            string value = port.IsValueType ? $"{name}.Value" : name;
            s.AppendLine(
                $"        if ({name} is not null) {{ inputs[\"{port.Key}\"] = {port.Write(value)}; }}"
            );
        }

        s.AppendLine("    }");
        s.AppendLine();
        string flowDefault = flows.Count == 0 ? "null" : $"\"{flows[0].Key}\"";
        s.AppendLine(
            "    /// <summary>Runs this node type once with the inputs set here.</summary>"
        );
        s.AppendLine("    /// <param name=\"client\">The connection.</param>");
        s.AppendLine(
            flows.Count == 0
                ? "    /// <param name=\"flowInput\">Unused: this node has no flow input.</param>"
                : $"    /// <param name=\"flowInput\">The flow input to run (<see cref=\"FlowInputs\"/>); <c>{Escape(flows[0].Key)}</c> by default.</param>"
        );
        s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
        s.AppendLine("    /// <returns>Its data outputs.</returns>");
        s.AppendLine(
            "    public async Task<Outputs> RunAsync(global::Warudo.Client.WarudoClient client, string? flowInput = null, CancellationToken ct = default) =>"
        );
        s.AppendLine(
            $"        new(await RunCoreAsync(client, flowInput ?? {flowDefault}, ct).ConfigureAwait(false));"
        );
        s.AppendLine();
        s.AppendLine("    /// <summary>The data outputs of a run.</summary>");
        s.AppendLine("    /// <param name=\"raw\">The outputs as the plugin sent them.</param>");
        s.AppendLine("    public sealed class Outputs(JsonElement raw)");
        s.AppendLine("    {");
        s.AppendLine("        /// <summary>The outputs as the plugin sent them.</summary>");
        s.AppendLine("        public JsonElement Raw { get; } = raw;");
        HashSet<string> outputNames = new(StringComparer.Ordinal) { "Raw" };
        foreach (Port port in outputs)
        {
            string name = Member(port.Key, "Outputs", outputNames);
            string type2 = port.IsEnum || port.Kind == "asset" ? "JsonElement" : port.ClientType;
            string read =
                port.IsEnum || port.Kind == "asset"
                    ? $"global::Warudo.Client.WarudoValue.Output(Raw, \"{port.Key}\")"
                    : port.Read($"global::Warudo.Client.WarudoValue.Output(Raw, \"{port.Key}\")");
            s.AppendLine();
            s.AppendLine(
                $"        /// <summary>The <c>{Escape(port.Key)}</c> data output{Label(port)}.</summary>"
            );
            s.AppendLine($"        public {type2} {name} => {read};");
        }

        s.AppendLine("    }");
        s.AppendLine("}");
        s.AppendLine();
    }

    // Each enum a type's inputs use, once, nested in the type and named as Warudo names it.
    private static void Enums(StringBuilder s, WarudoType type)
    {
        // An enum named like one of the type's ports would clash with that port's member.
        HashSet<string> members = new(
            type.Ports.Select(static p => Identifier(p.Key)),
            StringComparer.Ordinal
        )
        {
            type.Class,
        };
        foreach (Port port in type.Ports.Where(static p => p.IsEnum))
        {
            port.EnumAlias = members.Contains(port.EnumName)
                ? port.EnumName + "Option"
                : port.EnumName;
        }

        foreach (
            Port port in type
                .Ports.Where(static p => p.IsEnum && p.Section == "input")
                .GroupBy(static p => p.EnumName)
                .Select(static g => g.First())
        )
        {
            s.AppendLine();
            s.AppendLine($"    /// <summary>Warudo's <c>{Escape(port.ClrType)}</c>.</summary>");
            s.AppendLine($"    public enum {port.EnumName} : long");
            s.AppendLine("    {");
            foreach (string value in port.Values)
            {
                int equals = value.IndexOf('=');
                s.AppendLine(
                    $"        /// <summary><c>{Escape(value.Substring(0, equals))}</c>.</summary>"
                );
                s.AppendLine(
                    $"        {Identifier(value.Substring(0, equals))} = {value.Substring(equals + 1)},"
                );
            }

            s.AppendLine("    }");
        }
    }

    private static string Member(string key, string owner, HashSet<string> used)
    {
        string name = Identifier(key);
        if (_reserved.Contains(name) || name == owner)
        {
            name += "Value";
        }

        string unique = name;
        for (int i = 2; !used.Add(unique); i++)
        {
            unique = name + i.ToString(System.Globalization.CultureInfo.InvariantCulture);
        }

        return unique;
    }

    private static string Identifier(string text)
    {
        StringBuilder id = new();
        foreach (char c in text)
        {
            _ = id.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        }

        if (id.Length == 0 || char.IsDigit(id[0]))
        {
            _ = id.Insert(0, '_');
        }

        id[0] = char.ToUpperInvariant(id[0]);
        return id.ToString();
    }

    private static string Label(Port port) =>
        port.Label.Length == 0 ? string.Empty : $" (<c>{Escape(port.Label)}</c>)";

    private static string Escape(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private sealed class WarudoType(
        bool isNode,
        string @class,
        string id,
        string title,
        string category
    )
    {
        public bool IsNode { get; } = isNode;

        public string Class { get; } = Identifier(@class);

        public string Id { get; } = id;

        public string Title { get; } = title;

        public string Category { get; } = category;

        public List<Port> Ports { get; } = [];
    }

    private sealed class Port(
        string section,
        string key,
        string kind,
        string clrType,
        string label,
        string[] values
    )
    {
        public string Section { get; } = section;

        public string Key { get; } = key;

        public string Kind { get; } = kind;

        public string ClrType { get; } = clrType;

        public string Label { get; } = label;

        public string[] Values { get; } = values;

        public bool IsEnum => Kind == "enum" && Values.Length > 0;

        public string EnumName =>
            EnumAlias
            ?? Identifier(
                ClrType.Substring(Math.Max(ClrType.LastIndexOf('+'), ClrType.LastIndexOf('.')) + 1)
            );

        public string? EnumAlias { get; set; }

        public bool IsValueType => IsEnum || Kind is "bool" or "int" or "number" or "asset";

        public string ClientType =>
            IsEnum
                ? EnumName
                : Kind switch
                {
                    "bool" => "bool",
                    "int" => "int",
                    "number" => "double",
                    "string" => "string?",
                    "asset" => "Guid?",
                    _ => "JsonNode?",
                };

        public string Read(string element) =>
            IsEnum
                ? $"({EnumName})global::Warudo.Client.WarudoValue.ToEnumValue({element})"
                : Kind switch
                {
                    "bool" => $"global::Warudo.Client.WarudoValue.ToBoolean({element})",
                    "int" => $"global::Warudo.Client.WarudoValue.ToInt32({element})",
                    "number" => $"global::Warudo.Client.WarudoValue.ToDouble({element})",
                    "string" => $"global::Warudo.Client.WarudoValue.ToText({element})",
                    "asset" => $"global::Warudo.Client.WarudoValue.ToAssetId({element})",
                    _ => $"JsonNode.Parse(({element}).GetRawText())",
                };

        public string Write(string value) =>
            IsEnum
                ? $"global::Warudo.Client.WarudoValue.EnumReference((long){value})"
                : Kind switch
                {
                    "bool" or "int" or "number" or "string" => $"JsonValue.Create({value})",
                    "asset" => $"global::Warudo.Client.WarudoValue.AssetReference({value})",
                    _ => $"{value}?.DeepClone()",
                };

        public static Port? TryParse(string[] fields)
        {
            // fields[0] is the empty column before the indent tab.
            if (fields.Length < 3)
            {
                return null;
            }

            string section = fields[1];
            return section switch
            {
                "input" or "output" when fields.Length >= 5 => new Port(
                    section,
                    fields[2],
                    fields[3],
                    fields[4],
                    fields.Length > 5 ? fields[5] : string.Empty,
                    fields.Length > 6 && fields[6].Length > 0 ? fields[6].Split(',') : []
                ),
                "flowInput" or "flowOutput" => new Port(
                    section,
                    fields[2],
                    string.Empty,
                    string.Empty,
                    string.Empty,
                    []
                ),
                "trigger" => new Port(
                    section,
                    fields[2],
                    string.Empty,
                    string.Empty,
                    fields.Length > 3 ? fields[3] : string.Empty,
                    []
                ),
                _ => null,
            };
        }
    }
}
