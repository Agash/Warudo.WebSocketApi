using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Warudo.WebSocketApi.Generators;

/// <summary>
/// Reads <c>warudo-api.txt</c> and emits one side of the API: the plugin's <c>IWarudoApi</c> and dispatcher
/// (<c>WarudoApiSide=Server</c>, Newtonsoft, netstandard2.0) or <c>WarudoClient</c>'s typed methods
/// (<c>WarudoApiSide=Client</c>, System.Text.Json). One table keeps both sides in step.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class WarudoApiGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor _badLine = new(
        "WARUDOGEN001",
        "Unreadable API line",
        "Line {0} of warudo-api.txt is not 'method | parameters | result | summary': {1}",
        "Warudo.WebSocketApi.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true
    );

    private static readonly char[] _space = [' '];

    private static readonly string[] _types = ["string", "int", "double", "bool", "json", "guid"];

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<string> side = context.AnalyzerConfigOptionsProvider.Select(
            static (options, _) =>
                options.GlobalOptions.TryGetValue("build_property.WarudoApiSide", out string? value)
                    ? value
                    : string.Empty
        );
        IncrementalValuesProvider<string> tables = context
            .AdditionalTextsProvider.Where(static file =>
                file.Path.EndsWith("warudo-api.txt", StringComparison.OrdinalIgnoreCase)
            )
            .Select(static (file, ct) => file.GetText(ct)?.ToString() ?? string.Empty);
        context.RegisterSourceOutput(
            tables.Combine(side),
            static (spc, input) => Emit(spc, input.Left, input.Right)
        );
    }

    private static void Emit(SourceProductionContext context, string table, string side)
    {
        List<Method> methods = [];
        string[] lines = table.Split('\n');
        for (int index = 0; index < lines.Length; index++)
        {
            string line = lines[index].Trim();
            if (line.Length == 0 || line[0] == '#')
            {
                continue;
            }

            if (Method.TryParse(line) is { } method)
            {
                methods.Add(method);
            }
            else
            {
                context.ReportDiagnostic(
                    Diagnostic.Create(_badLine, Location.None, index + 1, line)
                );
            }
        }

        if (string.Equals(side, "Server", StringComparison.OrdinalIgnoreCase))
        {
            context.AddSource("IWarudoApi.g.cs", SourceText.From(Server(methods), Encoding.UTF8));
        }
        else if (string.Equals(side, "Client", StringComparison.OrdinalIgnoreCase))
        {
            context.AddSource(
                "WarudoClient.Api.g.cs",
                SourceText.From(Client(methods), Encoding.UTF8)
            );
        }
    }

    private static string Server(List<Method> methods)
    {
        StringBuilder s = new();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("using System;");
        s.AppendLine("using System.Threading.Tasks;");
        s.AppendLine("using Newtonsoft.Json.Linq;");
        s.AppendLine();
        s.AppendLine("namespace Warudo.WebSocketApi;");
        s.AppendLine();
        s.AppendLine(
            "/// <summary>What the plugin serves, one member per JSON-RPC method.</summary>"
        );
        s.AppendLine("public partial interface IWarudoApi");
        s.AppendLine("{");
        foreach (Method m in methods)
        {
            s.AppendLine($"    /// <summary>{Escape(m.Summary)} (<c>{m.Name}</c>)</summary>");
            s.AppendLine(
                $"    Task{m.ServerResult} {m.Pascal}Async({string.Join(", ", m.Parameters.Select(static p => $"{p.ServerType} {p.Name}"))});"
            );
            s.AppendLine();
        }

        s.AppendLine("}");
        s.AppendLine();
        s.AppendLine(
            "/// <summary>An <see cref=\"IWarudoApi\"/> that answers every method as not found; override the ones served.</summary>"
        );
        s.AppendLine("public abstract partial class WarudoApiBase : IWarudoApi");
        s.AppendLine("{");
        foreach (Method m in methods)
        {
            s.AppendLine("    /// <inheritdoc/>");
            s.AppendLine(
                $"    public virtual Task{m.ServerResult} {m.Pascal}Async({string.Join(", ", m.Parameters.Select(static p => $"{p.ServerType} {p.Name}"))}) => throw RpcException.MethodNotFound(\"{m.Name}\");"
            );
            s.AppendLine();
        }

        s.AppendLine("}");
        s.AppendLine();
        s.AppendLine(
            "/// <summary>Routes a JSON-RPC call to <see cref=\"IWarudoApi\"/>.</summary>"
        );
        s.AppendLine("public static partial class WarudoApiDispatcher");
        s.AppendLine("{");
        s.AppendLine("    /// <summary>Every method name the API serves.</summary>");
        s.AppendLine(
            $"    public static readonly string[] Methods = new[] {{ {string.Join(", ", methods.Select(static m => $"\"{m.Name}\""))} }};"
        );
        s.AppendLine();
        s.AppendLine("    /// <summary>Calls the method a request names.</summary>");
        s.AppendLine("    /// <param name=\"api\">The implementation.</param>");
        s.AppendLine("    /// <param name=\"method\">The JSON-RPC method.</param>");
        s.AppendLine("    /// <param name=\"parameters\">Its named parameters, or null.</param>");
        s.AppendLine(
            "    /// <returns>The result, or null for methods that return nothing.</returns>"
        );
        s.AppendLine(
            "    /// <exception cref=\"RpcException\">The method is unknown or a parameter is missing or of the wrong type.</exception>"
        );
        s.AppendLine(
            "    public static async Task<JToken?> DispatchAsync(IWarudoApi api, string method, JObject? parameters)"
        );
        s.AppendLine("    {");
        s.AppendLine("        switch (method)");
        s.AppendLine("        {");
        foreach (Method m in methods)
        {
            string args = string.Join(
                ", ",
                m.Parameters.Select(static p =>
                    $"RpcParameters.{(!p.Optional ? "Required" : p.IsValueType ? "OptionalValue" : "Optional")}<{p.ServerElementType}>(parameters, \"{p.Name}\")"
                )
            );
            s.AppendLine($"            case \"{m.Name}\":");
            if (m.Result.Length == 0)
            {
                s.AppendLine(
                    $"                await api.{m.Pascal}Async({args}).ConfigureAwait(false);"
                );
                s.AppendLine("                return null;");
            }
            else
            {
                s.AppendLine(
                    $"                return RpcParameters.ToToken(await api.{m.Pascal}Async({args}).ConfigureAwait(false));"
                );
            }
        }

        s.AppendLine("            default:");
        s.AppendLine("                throw RpcException.MethodNotFound(method);");
        s.AppendLine("        }");
        s.AppendLine("    }");
        s.AppendLine("}");
        return s.ToString();
    }

    private static string Client(List<Method> methods)
    {
        StringBuilder s = new();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("using System.Text.Json;");
        s.AppendLine("using System.Text.Json.Nodes;");
        s.AppendLine();
        s.AppendLine("namespace Warudo.Client;");
        s.AppendLine();
        s.AppendLine("public sealed partial class WarudoClient");
        s.AppendLine("{");
        foreach (Method m in methods)
        {
            s.AppendLine($"    /// <summary>{Escape(m.Summary)} (<c>{m.Name}</c>)</summary>");
            foreach (Parameter p in m.Parameters)
            {
                s.AppendLine(
                    $"    /// <param name=\"{p.Name}\">The <c>{p.Name}</c> parameter{(p.Optional ? "; optional" : string.Empty)}.</param>"
                );
            }

            s.AppendLine("    /// <param name=\"ct\">Cancels the wait for the reply.</param>");
            s.AppendLine(
                m.Result.Length == 0
                    ? "    /// <returns>When the plugin has answered.</returns>"
                    : "    /// <returns>The plugin's answer.</returns>"
            );
            string parameters = string.Join(
                ", ",
                m.Parameters.Select(static p =>
                        $"{p.ClientType} {p.Name}{(p.Optional ? " = null" : string.Empty)}"
                    )
                    .Concat(["global::System.Threading.CancellationToken ct = default"])
            );
            s.AppendLine(
                $"    public async global::System.Threading.Tasks.Task{m.ClientResult} {m.Pascal}Async({parameters})"
            );
            s.AppendLine("    {");
            s.AppendLine("        JsonObject parameters = new();");
            foreach (Parameter p in m.Parameters)
            {
                string assign = $"parameters[\"{p.Name}\"] = RpcValues.ToNode({p.Name});";
                s.AppendLine(
                    p.Optional
                        ? $"        if ({p.Name} is not null) {{ {assign} }}"
                        : $"        {assign}"
                );
            }

            s.AppendLine(
                $"        JsonElement result = await CallAsync(\"{m.Name}\", parameters, ct).ConfigureAwait(false);"
            );
            s.AppendLine(
                m.Result.Length == 0
                    ? "        _ = result;"
                    : $"        return RpcValues.{m.ClientReader}(result);"
            );
            s.AppendLine("    }");
            s.AppendLine();
        }

        s.AppendLine("}");
        return s.ToString();
    }

    private static string Escape(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private sealed record Parameter(string Type, string Name, bool Optional)
    {
        private bool IsList => Type.EndsWith("[]", StringComparison.Ordinal);

        private string Element => IsList ? Type.Substring(0, Type.Length - 2) : Type;

        public string ServerElementType =>
            Map(Element, server: true) + (IsList ? "[]" : string.Empty);

        public bool IsValueType => !IsList && Element is "int" or "double" or "bool" or "guid";

        public string ServerType => ServerElementType + (Optional ? "?" : string.Empty);

        public string ClientType =>
            (
                IsList
                    ? $"global::System.Collections.Generic.IReadOnlyList<{Map(Element, server: false)}>"
                    : Map(Element, server: false)
            ) + (Optional ? "?" : string.Empty);

        public static string Map(string type, bool server) =>
            type switch
            {
                "string" => "string",
                "int" => "int",
                "double" => "double",
                "bool" => "bool",
                "guid" => "global::System.Guid",
                _ => server ? "Newtonsoft.Json.Linq.JToken" : "JsonNode",
            };
    }

    private sealed record Method(
        string Name,
        ImmutableArray<Parameter> Parameters,
        ImmutableArray<Parameter> Result,
        string Summary
    )
    {
        public string Pascal =>
            string.Concat(
                Name.Split('.')
                    .Select(static part => char.ToUpperInvariant(part[0]) + part.Substring(1))
            );

        public string ServerResult =>
            Result.Length == 0 ? string.Empty : "<" + Result[0].ServerType + ">";

        public string ClientResult =>
            Result.Length == 0 ? string.Empty : "<" + ClientResultType + ">";

        private string ClientResultType =>
            Result[0].Type switch
            {
                "json" => "JsonElement",
                "string[]" => "string[]",
                "double[]" => "double[]",
                "int[]" => "int[]",
                var t => Parameter.Map(t, server: false),
            };

        public string ClientReader =>
            Result[0].Type switch
            {
                "json" => "Element",
                "string" => "String",
                "int" => "Int",
                "double" => "Double",
                "bool" => "Bool",
                "guid" => "Guid",
                "string[]" => "Strings",
                "double[]" => "Doubles",
                "int[]" => "Ints",
                _ => "Element",
            };

        public static Method? TryParse(string line)
        {
            string[] parts = line.Split('|').Select(static p => p.Trim()).ToArray();
            if (parts.Length != 4 || parts[0].Length == 0 || parts[0].IndexOf('.') <= 0)
            {
                return null;
            }

            ImmutableArray<Parameter>? parameters = Fields(parts[1]);
            ImmutableArray<Parameter>? result =
                parts[2] == "-" ? ImmutableArray<Parameter>.Empty : Fields(parts[2]);
            return parameters is null || result is null || result.Value.Length > 1
                ? null
                : new Method(parts[0], parameters.Value, result.Value, parts[3]);
        }

        private static ImmutableArray<Parameter>? Fields(string text)
        {
            ImmutableArray<Parameter>.Builder fields = ImmutableArray.CreateBuilder<Parameter>();
            foreach (string token in text.Split(_space, StringSplitOptions.RemoveEmptyEntries))
            {
                string[] typeAndName = token.Split(':');
                if (typeAndName.Length != 2)
                {
                    return null;
                }

                bool optional = typeAndName[0].EndsWith("?", StringComparison.Ordinal);
                string type = optional
                    ? typeAndName[0].Substring(0, typeAndName[0].Length - 1)
                    : typeAndName[0];
                string element = type.EndsWith("[]", StringComparison.Ordinal)
                    ? type.Substring(0, type.Length - 2)
                    : type;
                if (Array.IndexOf(_types, element) < 0)
                {
                    return null;
                }

                fields.Add(new Parameter(type, typeAndName[1], optional));
            }

            return fields.ToImmutable();
        }
    }
}
